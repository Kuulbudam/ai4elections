def test_complete_mapping_has_no_issues_and_saves_template(api, world):
    up, _ = upload_and_finalize(api, world, DEMO)
    drain(world)
    body = {**GOOD_MAPPING, "save_as_template_name": f"Demo layout {uuid.uuid4().hex[:4]}"}
    r = api.put(
        f"/dataset-versions/{up['dataset_version_id']}/mapping",
        json=body,
        headers=H(world.a.users["analyst"]),
    )
    assert r.status_code == 200, r.text
    assert r.json()["issues"] == [] and r.json()["template_id"]
    assert version(world, up["dataset_version_id"])["mapping"]["fields"]["pu_code"] == "PU Code"


def test_mapping_reports_missing_and_duplicate_assignments(api, world):
    up, _ = upload_and_finalize(api, world, DEMO)
    drain(world)
    bad = {
        **GOOD_MAPPING,
        "fields": {
            **{k: v for k, v in GOOD_MAPPING["fields"].items() if k != "total_cast"},
            "ward": "LGA",
            "latitude": "Latitude",
        },
        "party_columns": [
            {"source_column": "Votes PA", "party_code": "PA"},
            {"source_column": "Votes PA", "party_code": "PA"},
            {"source_column": "Nope", "party_code": "PX"},
        ],
    }
    r = api.put(f"/dataset-versions/{up['dataset_version_id']}/mapping", json=bad, headers=H(world.a.users["admin"]))
    issues = r.json()["issues"]
    rules = {(i["rule_id"], i.get("field")) for i in issues}
    assert ("V001", "total_cast") in rules
    assert any(i["rule_id"] == "V001" and "together" in i["message"] for i in issues)
    assert any(i["rule_id"] == "V002" and "'LGA'" in i["message"] for i in issues)
    assert any(i["rule_id"] == "V002" and "PA is used twice" in i["message"] for i in issues)
    assert any(i["rule_id"] == "V001" and "'Nope' does not exist" in i["message"] for i in issues)


