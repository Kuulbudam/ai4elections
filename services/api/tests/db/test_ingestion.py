@pytest.mark.parametrize(
    "data,code",
    [
        (b"1,2,3\n4,5,6\n", "HEADER_NOT_FOUND"),
        (b"a,b,a\n1,2,3\n", "HEADER_DUPLICATE_COLUMNS"),
        (b"a,b\n", "NO_DATA_ROWS"),
        (b'a,b\n"unclosed,1\n', "MALFORMED_CSV"),
        (b"a,,c\n1,2,3\n", "HEADER_EMPTY_COLUMN"),
    ],
)
def test_malformed_csv_fails_ingest_safely(api, world, data, code):
    up, fin = upload_and_finalize(api, world, data)
    drain(world)
    v = version(world, up["dataset_version_id"])
    assert v["status"] == "ingest_failed"
    assert raw_count(world, up["dataset_version_id"]) == 0
    job = api.get(f"/jobs/{fin['ingestion_job']['id']}", headers=H(world.a.users["analyst"])).json()
    assert job["status"] == "failed" and job["error_code"] == code and job["retryable"] is False


def test_tampered_stored_file_is_detected(api, world):
    up, fin = upload_and_finalize(api, world, SMALL)
    path = version(world, up["dataset_version_id"])["storage_path"]
    api.storage.objects[path] = SMALL.replace(b"500", b"900")  # simulate out-of-band change
    drain(world)
    job = api.get(f"/jobs/{fin['ingestion_job']['id']}", headers=H(world.a.users["analyst"])).json()
    assert job["status"] == "failed" and job["error_code"] == "INTEGRITY_MISMATCH"
    assert raw_count(world, up["dataset_version_id"]) == 0


