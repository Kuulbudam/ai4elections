def test_rate_limit_returns_429(api, world, monkeypatch):
    monkeypatch.setattr(deps, "USER_LIMIT_PER_MIN", 3)
    uid = world.a.users["viewer"]
    with psycopg.connect(world.dsn, autocommit=True) as c:
        c.execute("DELETE FROM app.rate_limits")
    codes = [api.get(f"/jobs/{uuid.uuid4()}", headers=H(uid)).status_code for _ in range(5)]
    assert codes[:3] == [404, 404, 404] and 429 in codes[3:]
    assert api.get(f"/jobs/{uuid.uuid4()}", headers=H(uid)).json()["code"] == "RATE_LIMITED"


def test_upload_actions_are_audited_with_actor(api, world):
    up, _ = upload_and_finalize(api, world, SMALL)
    with psycopg.connect(world.dsn, row_factory=dict_row) as c:
        rows = c.execute(
            "SELECT action, actor_id::text FROM public.audit_events WHERE entity_id=%s ORDER BY seq",
            (up["dataset_version_id"],),
        ).fetchall()
    actions = [r["action"] for r in rows]
    assert actions[:2] == ["dataset_versions.insert", "dataset_versions.update"]
    assert {r["actor_id"] for r in rows[:2]} == {world.a.users["analyst"]}
