class Dispatches(list):
    def __call__(self, job_id: str) -> str:
        self.append(job_id)
        return "ok"


@pytest.fixture()
def api(world, monkeypatch):
    monkeypatch.setenv("LEDGER_SCHEMA", "public")
    storage = MemoryStorage()
    dispatched = Dispatches()

    def db():
        c = psycopg.connect(world.dsn, autocommit=True, row_factory=dict_row)
        try:
            yield c
        finally:
            c.close()

    def user(request: Request) -> auth.CurrentUser:
        uid = request.headers.get("X-Test-User")
        if not uid:
            raise HTTPException(status_code=401, detail="Missing or invalid access token")
        return auth.CurrentUser(id=uid, email=None, claims={})

    app.dependency_overrides[deps.get_db] = db
    app.dependency_overrides[deps.get_storage] = lambda: storage
    app.dependency_overrides[deps.get_dispatcher] = lambda: dispatched
    app.dependency_overrides[auth.current_user] = user
    monkeypatch.setattr(deps, "_storage", storage)  # the worker uses deps.get_storage()
    client = TestClient(app, raise_server_exceptions=False)
    client.storage, client.dispatched = storage, dispatched
    yield client
    app.dependency_overrides.clear()


def H(uid: str, key: str | None = None) -> dict:
    h = {"X-Test-User": uid}
    if key:
        h["Idempotency-Key"] = key
    return h


def start_upload(
    api, world, data: bytes, role="analyst", dataset_id=None, name="SYNTHETIC_results.csv", key=None, **extra
):
    body = {
        "project_id": world.a.rows["projects"],
        "dataset_id": dataset_id,
        "dataset_name": None if dataset_id else f"Results {uuid.uuid4().hex[:6]}",
        "original_filename": name,
        "size_bytes": max(1, len(data)),
        "content_type": "text/csv",
        "source_type": "synthetic",
        "source_description": "SYNTHETIC demo data generated by tools/synthetic/generate.py",
        **extra,
    }
    return api.post("/uploads", json=body, headers=H(world.a.users[role], key))


def upload_and_finalize(api, world, data: bytes, **kw):
    r = start_upload(api, world, data, **kw)
    assert r.status_code == 201, r.text
    up = r.json()
    path = next(p for p in api.storage.signed if up["dataset_version_id"] in p)
    api.storage.put(path, data)
    f = api.post(f"/dataset-versions/{up['dataset_version_id']}/finalize", headers=H(world.a.users["analyst"]))
    assert f.status_code == 200, f.text
    return up, f.json()


def drain(world):
    with psycopg.connect(world.dsn, autocommit=True, row_factory=dict_row) as c:
        return worker.drain(c, "test-worker", max_jobs=None, stale_seconds=60)


def version(world, vid):
    with psycopg.connect(world.dsn, row_factory=dict_row) as c:
        return c.execute("SELECT * FROM public.dataset_versions WHERE id=%s", (vid,)).fetchone()


def raw_count(world, vid):
    with psycopg.connect(world.dsn) as c:
        return c.execute("SELECT count(*) FROM public.raw_rows WHERE dataset_version_id=%s", (vid,)).fetchone()[0]


# ------------------------------------------------------------------ happy path


def test_full_upload_finalize_ingest_of_demo_file(api, world):
    up, fin = upload_and_finalize(api, world, DEMO)
    vid = up["dataset_version_id"]
    assert up["version_number"] == 1
    assert fin["sha256"] == hashlib.sha256(DEMO).hexdigest()
    assert fin["size_bytes"] == len(DEMO)
    assert fin["status"] == "uploaded" and fin["ingestion_job"]["status"] == "queued"
    assert api.dispatched == [fin["ingestion_job"]["id"]]
    with psycopg.connect(world.dsn, row_factory=dict_row) as c:
        j = c.execute(
            "SELECT dispatch_result, dispatched_at FROM public.processing_jobs WHERE id=%s",
            (fin["ingestion_job"]["id"],),
        ).fetchone()
    assert j["dispatch_result"] == "ok" and j["dispatched_at"] is not None

    assert drain(world) >= 1
    v = version(world, vid)
    assert v["status"] == "ingested"
    assert v["row_count"] == 12_023 == raw_count(world, vid)
    assert v["header"]["columns"][0] == "PU Code" and v["header"]["delimiter"] == ","
    assert v["storage_path"] == f"{v['org_id']}/{v['project_id']}/{v['dataset_id']}/{vid}.csv"

    job = api.get(f"/jobs/{fin['ingestion_job']['id']}", headers=H(world.a.users["viewer"])).json()
    assert job["status"] == "succeeded" and job["progress"] == 1

    with psycopg.connect(world.dsn, row_factory=dict_row) as c:
        r = c.execute(
            "SELECT source_row_number, cells FROM public.raw_rows WHERE dataset_version_id=%s AND source_row_number=2",
            (vid,),
        ).fetchone()
        assert r["cells"][0] == "SY-01-01-01-00001"
        bad = c.execute(
            "SELECT cells FROM public.raw_rows WHERE dataset_version_id=%s AND cells ? 'abc'", (vid,)
        ).fetchone()
        assert bad is not None, "invalid values are preserved verbatim, never dropped"


def test_reupload_creates_new_immutable_version_and_flags_duplicate(api, world):
    up1, _ = upload_and_finalize(api, world, SMALL)
    up2, fin2 = upload_and_finalize(api, world, SMALL, dataset_id=up1["dataset_id"])
    assert up2["version_number"] == 2 and up2["dataset_version_id"] != up1["dataset_version_id"]
    assert fin2["duplicate_of_version_id"] == up1["dataset_version_id"]
    with pytest.raises(FileExistsError):  # the stored original cannot be overwritten
        api.storage.put(version(world, up1["dataset_version_id"])["storage_path"], b"tampered")


def test_finalize_is_one_time_and_repeat_returns_same_result(api, world):
    up, fin = upload_and_finalize(api, world, SMALL)
    again = api.post(f"/dataset-versions/{up['dataset_version_id']}/finalize", headers=H(world.a.users["analyst"]))
    assert again.status_code == 200
    assert again.json()["sha256"] == fin["sha256"]
    assert again.json()["ingestion_job"]["id"] == fin["ingestion_job"]["id"]


def test_idempotency_key_replays_upload(api, world):
    key = f"idem-{uuid.uuid4()}"
    a = start_upload(api, world, SMALL, key=key, dataset_name="Fixed name")
    b = start_upload(api, world, SMALL, key=key, dataset_name="Fixed name")
    assert a.status_code == b.status_code == 201
    assert a.json()["dataset_version_id"] == b.json()["dataset_version_id"]
    c = start_upload(api, world, SMALL, key=key, dataset_name="Different body")
    assert c.status_code == 409


def test_retrying_ingest_never_duplicates_rows(api, world):
    up, fin = upload_and_finalize(api, world, SMALL)
    drain(world)
    vid = up["dataset_version_id"]
    assert raw_count(world, vid) == 2
    # Force a second run of the same job (e.g. a duplicate dispatch after success).
    with psycopg.connect(world.dsn, autocommit=True) as c:
        c.execute(
            "UPDATE public.processing_jobs SET status='queued', finished_at=NULL WHERE id=%s",
            (fin["ingestion_job"]["id"],),
        )
    drain(world)
    assert raw_count(world, vid) == 2


